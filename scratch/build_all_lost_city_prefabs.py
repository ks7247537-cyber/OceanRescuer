def make_meta(path):
    meta = path + ".meta"
    if not os.path.exists(meta):
        g = uuid.uuid4().hex
        with open(meta, "w", encoding="utf-8") as f:
            f.write(f"fileFormatVersion: 2\nguid: {g}\nPrefabImporter:\n  externalObjects: {{}}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n")

def save_prefab(name, content):
    for folder in ['Assets/Prefab/LostCity', 'Assets/Resources/Prefabs']:
        os.makedirs(folder, exist_ok=True)
        path = f"{folder}/{name}.prefab"
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        make_meta(path)
        print(f"Saved {path}")

